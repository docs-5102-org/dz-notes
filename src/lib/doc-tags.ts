export const docTagDisplayMap: Record<string, string> = {
  ...commandTags,
  ...productTags,
  ...topicTags,
};

export function getTagDisplayName(tag: string) {
  return docTagDisplayMap[tag] ?? tag;
}

export function getDocFrontmatterTags(data: Record<string, unknown>) {
  const tags = data.tags ?? data.tag;
  return Array.isArray(tags) ? tags.filter((item): item is string => typeof item === 'string') : [];
}
